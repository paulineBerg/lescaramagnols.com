<p>Thanks to its 6x6 propulsion and its hydropneumatic systems, it adapted to difficult terrains. It was widely used in Africa, the Balkans, and Lebanon, and remains an emblematic model of Panhard\'s expertise in light intervention armored vehicles.</p>

