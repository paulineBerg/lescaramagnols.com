<h4>1960–2012: From the road to armored vehicles</h4>
<p>While civilian cars gradually faded, Panhard found a new path in the field of defense. From the 1950s, the company developed a series of light, robust, maneuverable, and exportable armored vehicles, becoming a discreet but strategic pillar of the French military industry.</p>

<h5>EBR (Engin Blindé de Reconnaissance - Armored Reconnaissance Vehicle) – 1951</h5>
<p>Launched in the context of the Cold War, the EBR is an 8x8 wheeled armored reconnaissance vehicle, designed for vast operational terrains. It is equipped with an oscillating chassis, eight wheels, four of which are retractable for the road, and above all a powerful 75 mm cannon (or 90 mm for later versions).</p>
<p>Powered by a 200 hp Panhard 12H engine, the EBR reached a top speed of 105 km/h. Its range (650 km) and its independent suspension made it a fast mobility tool. More than 1,200 units were produced and remained in service until the 1980s.</p>

<h5>AML (Auto Mitrailleuse Légère - Light Armored Car) – 1961</h5>
<p>Developed to meet the needs of asymmetrical conflicts, the AML is a compact four-wheel drive armored car, with varied armament depending on the versions: 90 mm cannon (AML-90), 60 mm mortar (AML-60), or twin machine guns.</p>
<p>Light, rugged, and easy to maintain, the AML was a huge export success: more than 4,000 units were delivered to more than 30 countries. Used in conflicts in Africa, the Middle East, and Asia, it became an emblem of French military diplomacy.</p>

<h5>VBL (Véhicule Blindé Léger - Light Armored Vehicle) – 1985</h5>
<p>With the rise of external operations and the need for discreet reconnaissance, the VBL marked a new turning point. Compact, amphibious, protected against mines and light fire, it could carry three soldiers and offered NBC protection (nuclear, biological, chemical).</p>
<p>Powered by a 95 hp Peugeot XD3T turbo diesel, the VBL could reach 95 km/h on the road, and 5 km/h in the water thanks to its hydrojet propulsion. Still in service in the French army, it is suitable for electronic warfare, observation, or tactical liaison.</p>

<h5>ERC-90 "Sagaie" – 1977</h5>
