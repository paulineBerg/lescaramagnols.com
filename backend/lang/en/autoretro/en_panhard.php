<p>Panhard became the first brand to mass-produce cars with a separate chassis and an efficient transmission. From 1894, the company participated in the Paris-Rouen race, then won the mythical Paris-Bordeaux-Paris in 1895 thanks to the tenacity of Émile Levassor.</p>

