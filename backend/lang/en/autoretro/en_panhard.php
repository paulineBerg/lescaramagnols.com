<p>In the last years of the 19th century, while the French industrial era was in full swing, two visionary men, René Panhard and Émile Levassor, founded a mechanical engineering company in 1887. Initially dedicated to machine tools, the company pivoted in 1891 to the automobile, using a Daimler license for its two-cylinder engine.</p>

